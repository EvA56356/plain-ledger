package cn.plainledger;

/** Regression scenarios use monotonic fake time, not sleeps or mocked Android services. */
public class PaymentScanSessionTest {
 private static int checks;
 private static void check(boolean condition, String message) { checks++; if (!condition) throw new AssertionError(message); }
 private static java.util.List<String> text(String... values) { return java.util.Arrays.asList(values); }
 public static void main(String[] args) {
  PaymentScanSession s = new PaymentScanSession();
  check(!s.active(100), "No observations at startup");
  s.observe("com.tencent.mm", "WalletOrderInfoNewUI", 100);
  long first = s.token();
  check(s.active(3100), "Late rendering without more events must still be scanned");
  s.remember(7, "支付成功\n¥12.34", 200); s.remember(7, "animation", 300);
  check(s.recent(7, 400).size() == 2, "Partial child event must not overwrite the receipt event");
  check(s.recent(8, 400).isEmpty(), "Never mix event text from another window");
  check(s.recent(7, 2001).isEmpty(), "Old success events must expire");
  s.observe("com.tencent.mm", "", 3000);
  check(s.accepts(first, "com.tencent.mm", 4000), "Child updates must not invalidate in-flight OCR");
  s.observe("com.tencent.mm", "LauncherUI", 4500);
  check(!s.accepts(first, "com.tencent.mm", 4600), "Navigation must discard stale OCR");
  long second = s.token(); s.stop();
  check(!s.accepts(second, "com.tencent.mm", 4700), "Leaving app cancels callbacks");
  s.observe("com.tencent.mm", "WalletOrderInfoNewUI", 5000);
  check(!s.accepts(first, "com.tencent.mm", 5100), "Returning to same activity is a new session");
  check(!s.active(21000), "Idle polling is bounded");
  check(!PaymentScanSession.supported("chat.app") && PaymentScanSession.supported("com.eg.android.AlipayGphone"), "Allowlist boundary");
  java.util.List<String> success = java.util.Arrays.asList("支付成功\n¥12.34");
  check(PaymentScanSession.resolve(java.util.Collections.emptyList(),success).amount == 1234, "Event-only receipt still works");
  check(PaymentScanSession.resolve(java.util.Arrays.asList("支付成功"),success).amount == 1234, "Event amount fills incomplete success window");
  check(PaymentScanSession.resolve(java.util.Arrays.asList("支付失败"),success).amount == 0, "Failure must override stale success event");
  check(PaymentScanSession.resolve(java.util.Arrays.asList("微信首页"),success).amount == 0, "Navigated page must override stale success event");
  check(PaymentScanSession.resolve(java.util.Arrays.asList("支付成功\n¥19.90"),success).amount == 1990, "Live receipt outranks older event");
  check(PaymentScanSession.resolve(java.util.Arrays.asList("支付成功\n¥12.34\n¥19.90"),success).amount == 0, "Ambiguity must not be hidden by an event");
  check(PaymentParser.parse("朋友说支付成功12.34元\n按住说话") == 0, "Accessible chat text must be excluded too");
  s.observe("com.tencent.mm", "WalletOrderInfoNewUI", 22000); s.window(7); long beforeWindow = s.token(); s.window(8);
  check(!s.accepts(beforeWindow,"com.tencent.mm",22500), "Window replacement in same activity must invalidate OCR");
  PaymentWindowOwnership owners = new PaymentWindowOwnership();
  owners.observe(7,"com.tencent.mm",100);
  check(owners.owner(7,3000).equals("com.tencent.mm"),"Focused rootless surface can use matching event identity");
  check(owners.owner(8,3000).isEmpty(),"Never apply one event identity to another window");
  owners.observe(7,"chat.app",4000);
  check(owners.owner(7,4100).equals("chat.app"),"Window ID reuse replaces prior payment identity");
  check(owners.owner(7,20000).isEmpty(),"Old event identity cannot authorize screenshots indefinitely");
  owners.observe(-1,"com.tencent.mm",21000);
  check(owners.owner(-1,21000).isEmpty(),"Unknown window IDs cannot authorize screenshots");
  java.util.List<String> empty = java.util.Collections.emptyList();
  check(PaymentScanSession.resolve(empty,text("支付成功\n¥12.34","支付失败")).amount == 0,"Rootless newer failure must veto cached success");
  check(PaymentScanSession.resolve(empty,text("支付成功\n¥12.34","朋友说支付成功12.34元\n按住说话")).amount == 0,"Rootless chat evidence must veto cached success");
  check(PaymentScanSession.resolve(empty,text("支付成功\n¥12.34","支付成功\n¥12.34\n¥19.90")).amount == 0,"Rootless ambiguous event must veto cached success");
  PaymentScanSession storm = new PaymentScanSession();storm.observe("com.tencent.mm","WalletOrderInfoNewUI",0);storm.window(77);
  check(storm.remember(77,"支付成功\n¥12.33",10),"A strong receipt requests an earlier scan");
  for(int i=1;i<=30;i++)storm.remember(77,"animation fragment "+i,10+i*35);
  check(PaymentScanSession.resolve(empty,storm.recent(77,1110)).amount==1233,"Thirty 35 ms animation events must not evict a receipt before the pending scan");
  check(storm.recent(77,1600).stream().noneMatch(t->t.contains("12.33")),"Strong event evidence still expires after 1.5 seconds");
  storm.remember(77,"支付成功\n¥12.33",2000);storm.remember(77,"支付失败",2010);
  for(int i=1;i<=30;i++)storm.remember(77,"noise "+i,2010+i*35);
  check(PaymentScanSession.resolve(empty,storm.recent(77,3110)).amount==0,"A newer failure clears the strong success and itself survives a storm");
  storm.remember(77,"支付成功\n¥18.88",3120);
  check(PaymentScanSession.resolve(empty,storm.recent(77,3130)).amount==1888,"A later complete success supersedes earlier failure evidence");
  storm.remember(78,"支付成功\n¥22.22",3140);storm.remember(77,"支付失败",3150);
  check(PaymentScanSession.resolve(empty,storm.recent(78,3160)).amount==2222,"A different window's failure cannot clear a receipt");
  long expired=storm.token();storm.observe("com.tencent.mm","WalletOrderInfoNewUI",20000);
  check(!storm.accepts(expired,"com.tencent.mm",20001),"A new observation cannot revive OCR from an expired watch");
  check(PaymentScanSession.ocrAllowed(empty,empty,"LauncherUI"),"A rootless focused payment window can use OCR");
  check(!PaymentScanSession.ocrAllowed(text("微信首页\n通讯录\n发现"),empty,"LauncherUI"),"Readable home pages do not continuously run OCR");
  check(!PaymentScanSession.ocrAllowed(text("朋友讨论支付\n按住说话"),empty,"LauncherUI"),"Payment words in chat do not permit OCR");
  check(PaymentScanSession.ocrAllowed(text("订单详情"),empty,"WalletOrderInfoNewUI"),"A payment Activity can contain partially exposed receipt text");
  check(PaymentScanSession.ocrAllowed(text("交易成功"),empty,"LauncherUI"),"A transaction-success clue permits OCR for a hidden amount");
  check(!PaymentScanSession.ocrAllowed(empty,text("支付失败"),"WalletOrderInfoNewUI"),"A rootless failed payment cannot authorize screenshots");
  java.util.List<String> partial=text("支付成功\n付款方式");
  check(PaymentScanSession.acceptsOcr(1234,partial,partial,empty,"WalletOrderInfoNewUI"),"An unchanged partial receipt can obtain its hidden amount from OCR");
  check(!PaymentScanSession.acceptsOcr(1234,partial,text("支付失败"),empty,"WalletOrderInfoNewUI"),"Late OCR cannot override same-window failure");
  check(!PaymentScanSession.acceptsOcr(1234,partial,text("支付成功12.34元\n按住说话"),empty,"WalletOrderInfoNewUI"),"Late OCR cannot override same-window chat navigation");
  check(!PaymentScanSession.acceptsOcr(1234,partial,text("支付成功\n¥12.34\n¥19.90"),empty,"WalletOrderInfoNewUI"),"Late OCR cannot hide current ambiguity");
  check(!PaymentScanSession.acceptsOcr(1234,partial,text("微信首页"),empty,"WalletOrderInfoNewUI"),"A payment Activity name cannot make changed homepage text accept old OCR");
  check(!PaymentScanSession.acceptsOcr(1234,partial,text("支付成功\n付款方式\n另一个订单"),empty,"WalletOrderInfoNewUI"),"Changed incomplete text requires a fresh image");
  check(PaymentScanSession.acceptsOcr(1234,partial,success,empty,"WalletOrderInfoNewUI"),"A current readable matching receipt remains authoritative");
  check(!PaymentScanSession.acceptsOcr(1234,partial,text("支付成功\n¥19.90"),empty,"WalletOrderInfoNewUI"),"A current different amount rejects old OCR");
  check(!PaymentScanSession.acceptsOcr(1234,empty,empty,text("支付失败"),"WalletOrderInfoNewUI"),"Rootless OCR must obey new failure evidence");
  check(!PaymentScanSession.acceptsOcr(1234,partial,partial,text("支付失败"),"WalletOrderInfoNewUI"),"A stale partial root cannot override a new failure event");
  PaymentScanSession handled=new PaymentScanSession();handled.observe("com.tencent.mm","WalletOrderInfoNewUI",0);handled.window(77);handled.markHandled(1234,partial);
  check(handled.pageHandled(partial,empty),"An already delivered OCR page stops repeated screenshots");
  check(handled.pageHandled(empty,empty),"Temporarily missing roots must not reopen an already handled page");
  check(!handled.pageHandled(text("支付成功\n¥19.90"),empty),"A genuinely different amount remains eligible");
  handled.markHandled(1234,empty);
  check(!handled.pageHandled(empty,text("支付失败")),"A newer rootless failure clears the handled page identity");
  handled.markHandled(1234,partial);
  check(!handled.pageHandled(text("微信首页"),empty),"Readable navigation clears the handled-page marker");
  handled.markHandled(1234,partial);handled.observe("com.tencent.mm","WalletOrderInfoNewUI",20000);
  check(handled.pageHandled(partial,empty),"Idle watch renewal does not resubmit the same handled page");
  handled.window(78);
  check(!handled.pageHandled(partial,empty),"A replaced window clears handled-page suppression");
  PaymentScanSession auth=new PaymentScanSession();
  auth.observe("com.tencent.mm","WalletPasswordActivity",7,0);auth.window(7);
  check(auth.sensitiveActivity(),"A matching authentication Activity remains protected");
  auth.observe("com.tencent.mm","",8,100);auth.window(8);
  check(auth.activity().isEmpty()&&auth.sensitiveActivity(),"A replacement window drops the stale Activity name but keeps an unknown-auth boundary");
  auth.confirmPaymentSurface(empty,empty,false);
  check(auth.sensitiveActivity(),"A rootless unknown replacement cannot authorize OCR merely by changing window ID");
  auth.confirmPaymentSurface(text("请输入支付密码"),success,false);
  check(auth.sensitiveActivity(),"A current authentication prompt overrides old successful events");
  auth.confirmPaymentSurface(success,empty,true);
  check(auth.sensitiveActivity(),"Visible password fields override receipt-like text");
  auth.confirmPaymentSurface(success,empty,false);
  check(!auth.sensitiveActivity(),"A current completed receipt releases only the stale authentication hint");
  auth.observe("com.tencent.mm","WalletPasswordActivity",9,200);auth.window(9);
  auth.observe("com.tencent.mm","WalletPasswordActivity",10,300);auth.window(10);
  auth.confirmPaymentSurface(success,empty,false);
  check(auth.sensitiveActivity(),"An explicitly observed new authentication Activity cannot be bypassed by receipt text");
  auth.observe("com.tencent.mm","",11,400);auth.window(11);
  auth.confirmPaymentSurface(text("支付成功\n付款方式\n完成"),empty,false);
  check(!auth.sensitiveActivity(),"A new completed receipt layout can allow OCR of a hidden amount without another Activity event");
  auth.observe("com.tencent.mm","WalletPasswordActivity",12,500);auth.window(12);
  auth.observe("com.tencent.mm","",13,600);auth.window(13);
  auth.confirmPaymentSurface(empty,text("支付成功\n付款方式"),false);
  check(!auth.sensitiveActivity(),"Rootless completion can use recent evidence from the matching new window");
  PaymentScanSession earlyAuth=new PaymentScanSession();earlyAuth.observe("com.tencent.mm","WalletPasswordActivity",7,0);earlyAuth.window(8);
  earlyAuth.confirmPaymentSurface(success,empty,false);
  check(!earlyAuth.sensitiveActivity(),"An already vanished authentication window need not have been scanned to detect its stale hint");
  auth.observe("com.tencent.mm","WalletPasswordActivity",14,700);auth.window(14);auth.window(15);
  auth.observe("com.tencent.mm","WalletOrderInfoNewUI",15,800);
  check(!auth.sensitiveActivity(),"A new explicit non-authentication Activity establishes its own window identity");
  System.out.println(checks+" observation, window ownership, event-storm, OCR freshness and delivery suppression scenarios passed");
 }
}
